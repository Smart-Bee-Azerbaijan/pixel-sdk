// Nativ nüvələrin mənbə kodunu örtük paketlərinə (React Native, Flutter) kopyalayır.
// Örtüklər npm / pub.dev paketi kimi dərc olunur və öz qovluğundan kənardakı fayllara istinad edə bilmir,
// ona görə nüvənin nüsxəsi onların içində saxlanır. Nüsxələr əl ilə dəyişdirilmir.
//
//   node mobile/sync-native.mjs           nüsxələri yeniləyir
//   node mobile/sync-native.mjs --check   nüsxələr köhnədirsə xəta ilə çıxır (CI üçün)
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes('--check');
const HEADER = '// GENERATED by mobile/sync-native.mjs. Mənbə: {src}. Bu faylı dəyişməyin.\n';

const androidSrc = 'android/pixel/src/main/java/az/smartbee/pixel';
const iosSrc = 'ios/Sources/SmartBeePixel';

/** [mənbə qovluğu, fayl uzantısı, hədəf qovluğu, başlıq əlavə olunsun?] */
const copies = [
  [androidSrc, '.kt', 'react-native/android/src/main/java/az/smartbee/pixel', true],
  [androidSrc, '.kt', 'flutter/android/src/main/kotlin/az/smartbee/pixel', true],
  [iosSrc, '.swift', 'react-native/ios/Core', true],
  [iosSrc, '.swift', 'flutter/ios/Classes/Core', true],
  [iosSrc, '.xcprivacy', 'react-native/ios/Resources', false],
  [iosSrc, '.xcprivacy', 'flutter/ios/Resources', false],
];

let stale = 0;
let written = 0;
for (const [src, ext, dest, withHeader] of copies) {
  const srcDir = join(root, src);
  const destDir = join(root, dest);
  const names = readdirSync(srcDir).filter((name) => name.endsWith(ext)).sort();
  if (names.length === 0) throw new Error(`${src}: ${ext} faylı tapılmadı`);

  // Mənbədə artıq olmayan nüsxələr silinir.
  if (existsSync(destDir)) {
    for (const name of readdirSync(destDir).filter((n) => n.endsWith(ext))) {
      if (!names.includes(name)) {
        if (check) stale++;
        else rmSync(join(destDir, name));
      }
    }
  }

  for (const name of names) {
    const body = readFileSync(join(srcDir, name), 'utf8').replace(/\r\n/g, '\n');
    const content = withHeader ? HEADER.replace('{src}', `mobile/${src}/${name}`) + body : body;
    const target = join(destDir, name);
    const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current === content) continue;
    if (check) {
      stale++;
      console.error(`köhnədir: mobile/${dest}/${name}`);
    } else {
      mkdirSync(destDir, { recursive: true });
      writeFileSync(target, content);
      written++;
    }
  }
}

if (check) {
  if (stale) {
    console.error(`${stale} fayl köhnədir. İşlədin: node mobile/sync-native.mjs`);
    process.exit(1);
  }
  console.log('nüsxələr mənbə ilə eynidir');
} else {
  console.log(`${written} fayl yeniləndi`);
}
