// Copies the source code of the native cores into the wrapper packages (React Native, Flutter).
// The wrappers are published as npm / pub.dev packages and cannot reference files outside their own directory,
// so a copy of the core is kept inside each of them. The copies are never edited by hand.
//
//   node mobile/sync-native.mjs           refreshes the copies
//   node mobile/sync-native.mjs --check   exits with an error when the copies are stale (for CI)
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes('--check');
const HEADER = '{mark} GENERATED by mobile/sync-native.mjs. Source: {src}. Do not edit this file.\n';

const androidSrc = 'android/pixel/src/main/java/az/smartbee/pixel';
const iosSrc = 'ios/Sources/SmartBeePixel';
// R8 / ProGuard rules: the wrappers carry the source code of the native SDK, not its AAR, so the rules for the
// classes that are read by reflection must reach the app together with them.
const androidRules = 'consumer-rules.pro';

/**
 * [source directory, end of the file name (extension or full name), target directory, add the header?]
 * The header comment starts with `#` in `.pro` files and with `//` in the others.
 */
const copies = [
  [androidSrc, '.kt', 'react-native/android/src/main/java/az/smartbee/pixel', true],
  [androidSrc, '.kt', 'flutter/android/src/main/kotlin/az/smartbee/pixel', true],
  ['android/pixel', androidRules, 'react-native/android', true],
  ['android/pixel', androidRules, 'flutter/android', true],
  [iosSrc, '.swift', 'react-native/ios/Core', true],
  [iosSrc, '.swift', 'flutter/ios/Classes/Core', true],
  [iosSrc, '.xcprivacy', 'react-native/ios/Resources', false],
  [iosSrc, '.xcprivacy', 'flutter/ios/Resources', false],
];

let stale = 0;
let written = 0;
for (const [src, ext, dest, withHeader] of copies) {
  const srcDir = join(root, src);
  const destDir = join(root, dest);
  const names = readdirSync(srcDir).filter((name) => name.endsWith(ext)).sort();
  if (names.length === 0) throw new Error(`${src}: no ${ext} file found`);

  // Copies whose source no longer exists are removed.
  if (existsSync(destDir)) {
    for (const name of readdirSync(destDir).filter((n) => n.endsWith(ext))) {
      if (!names.includes(name)) {
        if (check) stale++;
        else rmSync(join(destDir, name));
      }
    }
  }

  for (const name of names) {
    const body = readFileSync(join(srcDir, name), 'utf8').replace(/\r\n/g, '\n');
    const header = HEADER.replace('{mark}', name.endsWith('.pro') ? '#' : '//').replace('{src}', `mobile/${src}/${name}`);
    const content = withHeader ? header + body : body;
    const target = join(destDir, name);
    const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current === content) continue;
    if (check) {
      stale++;
      console.error(`stale: mobile/${dest}/${name}`);
    } else {
      mkdirSync(destDir, { recursive: true });
      writeFileSync(target, content);
      written++;
    }
  }
}

if (check) {
  if (stale) {
    console.error(`${stale} file(s) are stale. Run: node mobile/sync-native.mjs`);
    process.exit(1);
  }
  console.log('the copies match their sources');
} else {
  console.log(`${written} file(s) updated`);
}
